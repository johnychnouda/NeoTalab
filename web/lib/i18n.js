/** Intl locale per UI language; Arabic keeps Latin digits like the rest of the app. */
export const LOCALES = { en: "en-GB", ar: "ar-LB-u-nu-latn", fr: "fr-FR" };

/** Fills {name} placeholders in a translated string. */
function fill(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
}

const LangContext = createContext({ lang: "en", locale: LOCALES.en, setLang: () => {}, t: (k) => k });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState("en");

  useEffect(() => {
    const cookie = document.cookie.match(/(?:^|; )nt_lang=(en|ar|fr)/)?.[1];
    let saved = null;
    try { saved = localStorage.getItem("nt_lang"); } catch { /* private mode */ }
    if (!cookie && saved) document.cookie = `nt_lang=${saved}; path=/; max-age=31536000; samesite=lax`;
    setLangState(cookie || saved || "en");
  }, []);

  useEffect(() => {
    const rtl = ["ar", "he", "fa", "ur"].includes(lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = rtl ? "rtl" : "ltr";
  }, [lang]);

  const setLang = (code) => {
    try { localStorage.setItem("nt_lang", code); } catch { /* private mode */ }
    // Shared with the server-rendered public pages, which read it to pick their language.
    document.cookie = `nt_lang=${code}; path=/; max-age=31536000; samesite=lax`;
    setLangState(code);
  };

  const dict = I18N[lang] || I18N.en;
  // `{n}` of 1 picks the "<key>_one" variant when this language has one ("1 payment", not "1 payments").
  const t = (key, vars) => fill((vars?.n === 1 && dict[`${key}_one`]) || dict[key] || I18N.en[key] || key, vars);

  return createElement(LangContext.Provider, { value: { lang, locale: LOCALES[lang] || LOCALES.en, setLang, t } }, children);
}

export function useLang() {
  return useContext(LangContext);
}
