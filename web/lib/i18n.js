const LangContext = createContext({ lang: "en", setLang: () => {}, t: (k) => k });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState("en");

  useEffect(() => {
    const saved = localStorage.getItem("nt_lang") || "en";
    setLangState(saved);
  }, []);

  useEffect(() => {
    const rtl = ["ar", "he", "fa", "ur"].includes(lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = rtl ? "rtl" : "ltr";
  }, [lang]);

  const setLang = (code) => {
    localStorage.setItem("nt_lang", code);
    setLangState(code);
  };

  const t = (key) => (I18N[lang] || I18N.en)[key] || I18N.en[key] || key;

  return createElement(LangContext.Provider, { value: { lang, setLang, t } }, children);
}

export function useLang() {
  return useContext(LangContext);
}
